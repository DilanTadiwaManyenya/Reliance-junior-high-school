for(const width of [320,390]) {
const learnerManagement=await openPortal(runtime.browser,runtime.base,{role:'admin',section:'roster',multiClassAllocations:''},width)
await learnerManagement.getByLabel('Search',{exact:true}).fill('Alexandra')
await learnerManagement.locator('.mobile-record-table tbody tr').getByRole('button',{name:'Edit',exact:true}).click()
await learnerManagement.getByRole('heading',{name:'Edit learner',exact:true,level:1}).waitFor()
const editMetrics=await portalLayoutMetrics(learnerManagement)
assert.ok(editMetrics.documentWidth<=width+1,`Learner edit must not cause horizontal scrolling at ${width}px`)
assert.deepEqual(editMetrics.clipped,[],`Learner edit controls must fit the ${width}px viewport`)
assert.ok(await learnerManagement.locator('form.portal-form select,form.portal-form input,form.portal-form button').evaluateAll(controls=>controls.every(control=>control.getBoundingClientRect().height>=43.99)),`Learner edit controls must remain easy to tap at ${width}px`)
await learnerManagement.getByLabel('Class level',{exact:true}).selectOption('Form 2')
await learnerManagement.getByLabel('Class stream',{exact:true}).selectOption('Green')
await learnerManagement.getByRole('button',{name:'Save changes',exact:true}).click()
await learnerManagement.getByRole('heading',{name:'Learner Roster',exact:true}).waitFor()
const movedLearner=learnerManagement.locator('.mobile-record-table tbody tr').filter({hasText:'Alexandra Example Learner With A Longer Name'})
await movedLearner.waitFor()
assert.match(await movedLearner.innerText(),/Form 2[\s\S]*Green/,'Saved class and stream should be visible in the roster')
assert.equal(await learnerManagement.evaluate(() => window.fixtureWrites.some(row => row.table==='students'&&row.operation==='update'&&row.payload.class_level==='Form 2'&&row.payload.class_stream==='Green'&&row.payload.campus==='senior')),true,'Class move must persist class, stream and campus together')
await movedLearner.getByRole('button',{name:'Edit',exact:true}).click()
await learnerManagement.getByRole('heading',{name:'Edit learner',exact:true,level:1}).waitFor()
await learnerManagement.getByLabel('Class level',{exact:true}).selectOption('Grade 1')
assert.equal(await learnerManagement.getByLabel('Class stream',{exact:true}).isDisabled(),true,'Junior classes should not accept a Senior stream')
await learnerManagement.getByRole('button',{name:'Save changes',exact:true}).click()
await learnerManagement.getByRole('heading',{name:'Learner Roster',exact:true}).waitFor()
assert.equal(await learnerManagement.evaluate(() => window.fixtureWrites.some(row => row.table==='students'&&row.operation==='update'&&row.payload.class_level==='Grade 1'&&row.payload.class_stream===null&&row.payload.campus==='junior')),true,'Cross-campus class correction must update campus and clear the inapplicable stream')
assert.match(await learnerManagement.locator('.mobile-record-table tbody tr').filter({hasText:'Alexandra Example Learner With A Longer Name'}).innerText(),/Grade 1/)
learnerManagement.once('dialog',dialog=>dialog.accept('Placed in the wrong class; correcting the record.'))
await movedLearner.getByRole('button',{name:'Disable learner',exact:true}).click()
await learnerManagement.getByText('Alexandra Example Learner With A Longer Name',{exact:true}).waitFor()
assert.match(await movedLearner.innerText(),/Disabled for review|inactive/i)
await learnerManagement.evaluate(()=>{window.confirm=message=>(window.fixtureDeleteConfirmation=message,true);window.prompt=message=>(window.fixtureDeleteReasonPrompt=message,'Duplicate learner record entered in error.')})
await movedLearner.getByRole('button',{name:'Delete disabled learner',exact:true}).click()
await movedLearner.waitFor({state:'detached'})
assert.match(await learnerManagement.evaluate(()=>window.fixtureDeleteConfirmation),/cannot be undone/)
assert.match(await learnerManagement.evaluate(()=>window.fixtureDeleteReasonPrompt),/reason for permanently deleting/)
assert.equal(await learnerManagement.evaluate(() => window.fixtureWrites.some(row=>row.table==='rpc:correct_assigned_learner'&&row.payload.p_details.disable_reason)),true,'Admin disable should use the audited learner correction function')
assert.equal(await learnerManagement.evaluate(() => window.fixtureWrites.some(row=>row.table==='rpc:manage_disabled_learner'&&row.payload.p_action==='delete'&&row.payload.p_reason==='Duplicate learner record entered in error.')),true,'Permanent deletion must require and submit a reason')
assert.deepEqual(learnerManagement.portalErrors,[])
await learnerManagement.close()
console.log(`PASS learner administration at ${width}px: class/stream UI updates, cross-campus move, disable and reasoned deletion`)
}

