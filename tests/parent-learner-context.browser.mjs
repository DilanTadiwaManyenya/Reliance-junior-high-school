import assert from 'node:assert/strict'
import { mkdir } from 'node:fs/promises'
import { startPortalBrowser, openPortal } from './helpers/portal-browser.mjs'
const r=await startPortalBrowser()
try {
 const p=await openPortal(r.browser,r.base,{role:'parent',delayParent:''},390)
 await p.waitForFunction(()=>typeof window.fixtureResolveParent==='function')
 await p.getByRole('combobox',{name:'Viewing learner'}).selectOption('learner-1')
 await p.locator('.parent-record-launcher').waitFor()
 assert.match(await p.locator('h1').innerText(),/Brian/)
 assert.match(await p.locator('.parent-learner-context').innerText(),/Junior School/)
 await p.evaluate(()=>window.fixtureResolveParent())
 await p.waitForFunction(()=>window.fixtureRoute.includes('learner=learner-1'))
 assert.equal(await p.getByText('No coursework marks have been shared yet.',{exact:true}).count(),1)
 await p.locator('.parent-record-link').filter({hasText:'Course Work'}).click()
 await p.getByRole('link',{name:'← Back to dashboard',exact:true}).click()
 await p.getByRole('combobox',{name:'Viewing learner'}).waitFor()
 assert.equal(await p.getByRole('combobox',{name:'Viewing learner'}).inputValue(),'learner-1')
 await p.getByRole('link',{name:/Open uniform catalogue for Brian/}).click()
 await p.getByRole('combobox',{name:'Buying for'}).waitFor()
 assert.equal(await p.getByRole('combobox',{name:'Buying for'}).inputValue(),'learner-1')
 await p.getByRole('combobox',{name:'Buying for'}).selectOption('learner-0')
 await p.waitForFunction(()=>window.fixtureRoute.includes('learner=learner-0'))
 await p.getByRole('heading',{name:'Senior School uniforms',exact:true}).waitFor()
 assert.match(await p.locator('.parent-shop-heading').innerText(),/Alexandra Example Learner/)
 assert.equal(await p.locator('.parent-product-card').count(),1,'Changing campus should reload the selected learner’s catalog')
 await p.getByRole('link',{name:'← Back to dashboard',exact:true}).click()
 assert.equal(await p.getByRole('combobox',{name:'Viewing learner'}).inputValue(),'learner-0')
 await p.evaluate(()=>window.fixtureParentError=true)
 await p.getByRole('combobox',{name:'Viewing learner'}).selectOption('learner-2')
 await p.getByRole('button',{name:'Retry learner records',exact:true}).waitFor()
 assert.equal(await p.locator('.parent-record-launcher').count(),0,'Failed read must not imply unlocked report/empty balances')
 await p.evaluate(()=>window.fixtureParentError=false)
 await p.getByRole('button',{name:'Retry learner records',exact:true}).click()
 await p.locator('.parent-record-launcher').waitFor()
 assert.deepEqual(p.portalErrors,[])
 await mkdir('tmp/mobile-parent-review',{recursive:true})
 await p.screenshot({path:'tmp/mobile-parent-review/learner-context-390.png',fullPage:true})
 await p.close()
 const invalid=await openPortal(r.browser,r.base,{role:'parent',route:'/portal/dashboard?learner=unlinked'},320)
 assert.match(await invalid.locator('h1').innerText(),/Alexandra/)
 await invalid.close()
 const direct=await openPortal(r.browser,r.base,{role:'parent',route:'/portal/learner/learner-1/coursework'},320)
 await direct.locator('.portal-history-back').click()
 await direct.getByRole('combobox',{name:'Viewing learner'}).waitFor()
 assert.equal(await direct.getByRole('combobox',{name:'Viewing learner'}).inputValue(),'learner-1')
 await direct.close()
 console.log('PASS parent learner URL, late-response isolation, record/shop return paths, failed-read retry and invalid learner fallback')
}finally{await r.close()}
