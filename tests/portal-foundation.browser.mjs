import assert from 'node:assert/strict'
import { mkdir } from 'node:fs/promises'
import { startPortalBrowser } from './helpers/portal-browser.mjs'
const runtime=await startPortalBrowser()
await mkdir('tmp/mobile-foundation-review',{recursive:true})
try {
  for(const width of [320,390,768,1280]) {
    const page=await runtime.browser.newPage({viewport:{width,height:844},reducedMotion:'reduce'})
    page.setDefaultTimeout(15000)
    const errors=[];page.on('pageerror',error=>errors.push(error.message))
    await page.goto(`${runtime.base}/tests/fixtures/foundation/index.html`,{waitUntil:'domcontentloaded'})
    await page.getByRole('heading',{name:'Portal foundation reference'}).waitFor()
    const controls=await page.locator('.portal-foundation .ui-button').evaluateAll(elements=>elements.map(e=>({height:e.getBoundingClientRect().height,minHeight:getComputedStyle(e).minHeight})))
    assert.ok(controls.every(e=>e.height>=44 && e.minHeight==='44px'))
    assert.equal(await page.getByRole('button',{name:'Unavailable action'}).isDisabled(),true)
    assert.equal(await page.getByRole('link',{name:'Unavailable link'}).getAttribute('href'),null)
    await page.getByRole('button',{name:'Save details',exact:true}).click()
    const name=page.getByLabel('Full name',{exact:false})
    assert.equal(await name.getAttribute('aria-invalid'),'true')
    const described=await name.getAttribute('aria-describedby')
    assert.ok(described.includes('-hint') && described.includes('-error'))
    await page.getByRole('alert').filter({hasText:'Enter the learner full name.'}).waitFor()
    await name.fill('Alexandra Example Learner With A Very Long Full Name')
    await page.getByRole('button',{name:'Save details',exact:true}).click()
    await page.getByRole('status').filter({hasText:'Details saved'}).waitFor()
    await page.locator('.ui-filter-panel summary').click()
    await page.getByLabel('Search learners',{exact:true}).fill('Alexandra')
    const region=page.getByRole('region',{name:'Learner comparison'})
    await region.focus()
    assert.equal(await region.evaluate(e=>e===document.activeElement),true)
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),true)
    assert.equal(await page.getByRole('button',{name:'Public website button'}).evaluate(e=>getComputedStyle(e).minHeight),'40px','Public website does not inherit portal sizing')
    assert.equal(await page.getByRole('heading',{name:'Public website heading'}).evaluate(e=>{const before=getComputedStyle(e).fontSize;const parent=e.parentElement;parent.classList.remove('ui-section-heading');const baseline=getComputedStyle(e).fontSize;parent.classList.add('ui-section-heading');return before===baseline}),true,'Public section heading remains unchanged')
    console.log(`PASS shared controls and portal isolation at ${width}px`)
    const trigger=page.getByRole('button',{name:'Open learner details'})
    await trigger.click()
    const dialog=page.getByRole('dialog',{name:'Learner details panel'})
    await dialog.waitFor()
    console.log(`OPEN dialog at ${width}px`)
    const firstId=await dialog.getAttribute('aria-labelledby')
    assert.ok(await dialog.getAttribute('aria-describedby'))
    await page.setViewportSize({width,height:480})
    const save=dialog.getByRole('button',{name:'Save panel'})
    await save.scrollIntoViewIfNeeded()
    assert.ok(await save.evaluate(e=>{const b=e.getBoundingClientRect();return b.top>=0 && b.bottom<=innerHeight && e.contains(document.elementFromPoint(b.x+b.width/2,b.y+b.height/2))}),'Dialog save remains reachable above reduced viewport edge')
    await page.keyboard.press('Escape')
    await dialog.waitFor({state:'detached'})
    assert.equal(await trigger.evaluate(e=>e===document.activeElement),true)
    await page.getByRole('button',{name:'Open another panel'}).click()
    const second=page.getByRole('dialog',{name:'Another panel'})
    assert.notEqual(await second.getAttribute('aria-labelledby'),firstId)
    await page.keyboard.press('Escape')
    await second.waitFor({state:'detached'})
    await page.setViewportSize({width,height:844})
    await page.screenshot({path:`tmp/mobile-foundation-review/components-${width}.png`,fullPage:true})
    assert.deepEqual(errors,[])
    await page.close()
    console.log(`PASS foundation ${width}px: targets, semantics, validation, local table scroll, dialog focus/keyboard viewport and public-site isolation`)
  }
} finally {await runtime.close()}
