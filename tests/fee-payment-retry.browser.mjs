import assert from 'node:assert/strict'
import { startPortalBrowser, openPortal } from './helpers/portal-browser.mjs'
const runtime=await startPortalBrowser()
try {
 for(const width of [390,1280]) {
  const page=await openPortal(runtime.browser,runtime.base,{role:'admin',campus:'all',section:'fees',feeRetry:''},width)
  await page.getByRole('button',{name:'Collect payment',exact:true}).first().click()
  await page.getByLabel('New amount received',{exact:true}).fill('20')
  await page.getByRole('button',{name:'Record payment',exact:true}).click()
  await page.getByRole('button',{name:'Retry saved payment',exact:true}).waitFor()
  await page.getByRole('dialog').waitFor({state:'detached'})
  const original=await page.evaluate(()=>window.fixtureWrites.find(row=>row.table==='rpc:record_learner_fee_payment').payload)
  assert.ok(original.p_request_id)
  await page.reload()
  await page.getByRole('button',{name:'Retry saved payment',exact:true}).waitFor()
  await page.getByRole('button',{name:'Collect payment',exact:true}).first().click()
  assert.equal(await page.getByRole('dialog').count(),0)
  await page.getByRole('button',{name:'Retry saved payment',exact:true}).click()
  await page.getByRole('button',{name:'Retry saved payment',exact:true}).waitFor({state:'detached'})
  const retried=await page.evaluate(()=>window.fixtureWrites.find(row=>row.table==='rpc:record_learner_fee_payment').payload)
  assert.deepEqual(retried,original)
  assert.equal(await page.evaluate(()=>Object.keys(localStorage).filter(key=>key.startsWith('fixture-fee-server:')).length),1)
  assert.equal(await page.evaluate(()=>Object.keys(sessionStorage).filter(key=>key.startsWith('reliance:fee-payment:')).length),0)
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1))
  assert.deepEqual(page.portalErrors,[])
  console.log(`PASS fee payment ${width}px: lost response, reload, blocked new collection, identical retry and recovery cleanup`)
  await page.close()
 }
 const page=await openPortal(runtime.browser,runtime.base,{role:'admin',section:'fees',delayPayment:''},390)
 await page.getByRole('button',{name:'Collect payment',exact:true}).first().click()
 await page.getByLabel('New amount received',{exact:true}).fill('10')
 await page.getByRole('button',{name:'Record payment',exact:true}).click()
 await page.waitForFunction(()=>typeof window.fixtureResolvePayment==='function')
 assert.equal(await page.getByRole('dialog').getByRole('button',{name:'Cancel',exact:true}).isDisabled(),true)
 await page.keyboard.press('Escape')
 assert.equal(await page.getByRole('dialog').count(),1)
 assert.equal(await page.evaluate(()=>window.fixtureWrites.filter(row=>row.table==='rpc:record_learner_fee_payment').length),1)
 await page.evaluate(()=>window.fixtureResolvePayment())
 await page.getByRole('dialog').waitFor({state:'detached'})
 console.log('PASS pending fee payment cannot be dismissed or submitted twice')
 await page.close()
} finally { await runtime.close() }
