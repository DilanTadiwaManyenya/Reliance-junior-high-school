import assert from 'node:assert/strict'
import { mkdir } from 'node:fs/promises'
import { startPortalBrowser, openPortal, portalLayoutMetrics } from './helpers/portal-browser.mjs'
const runtime = await startPortalBrowser()
try {
  for (const width of [320,390,667,1280]) {
    const page = await openPortal(runtime.browser,runtime.base,{role:'admin',section:'activity'},width)
    await page.getByRole('button',{name:'Record changes',exact:true}).click()
    await page.locator('.record-history-event').first().waitFor()
    assert.equal(await page.locator('.record-history-event').count(),50)
    await page.locator('.record-history-event').first().getByText('View 1 changed field',{exact:true}).click()
    const field=page.locator('.record-history-field').first()
    assert.match(await field.innerText(),/Before\s+60\s+After\s+75/)
    await page.getByRole('button',{name:'Load more changes',exact:true}).click()
    await page.waitForFunction(()=>document.querySelectorAll('.record-history-event').length===51)
    await page.getByLabel('Learner name',{exact:true}).fill('Brian')
    await page.waitForFunction(()=>document.querySelectorAll('.record-history-event').length===1)
    assert.match(await page.locator('.record-history-event').innerText(),/Brian Example/)
    await page.getByLabel('Learner name',{exact:true}).fill('')
    await page.getByLabel('Record type',{exact:true}).selectOption('attendance')
    await page.waitForFunction(()=>document.querySelectorAll('.record-history-event').length===17)
    assert.match(await page.locator('.record-history-event').first().innerText(),/Attendance/)
    await page.getByLabel('From',{exact:true}).fill('2099-01-01')
    await page.getByText('No matching record changes.',{exact:true}).waitFor()
    await page.getByLabel('To',{exact:true}).fill('2098-01-01')
    await page.getByRole('alert').waitFor()
    assert.match(await page.getByRole('alert').innerText(),/end date/)
    await page.getByLabel('From',{exact:true}).fill('')
    await page.getByLabel('To',{exact:true}).fill('')
    await page.locator('.record-history-event').first().waitFor()
    await page.locator('.record-history-event').first().locator('summary').click()
    const metrics=await portalLayoutMetrics(page)
    assert.ok(metrics.documentWidth<=width+1,JSON.stringify(metrics))
    assert.deepEqual(metrics.clipped,[])
    assert.deepEqual(metrics.smallFields,[])
    if (width===390) { await mkdir('tmp/record-history-review',{recursive:true}); await page.screenshot({path:'tmp/record-history-review/history-390.png',fullPage:true}) }
    assert.deepEqual(page.portalErrors,[])
    assert.equal(await page.evaluate(()=>window.fixtureWrites.filter(row=>row.table==='school_record_changes').length),0)
    await page.getByRole('button',{name:'Portal activity',exact:true}).click()
    await page.getByRole('heading',{name:'Activity log',exact:true}).waitFor()
    await page.close()
    console.log(`PASS record history ${width}px: before/after, pagination, filters, validation and mobile layout`)
  }
  const error=await openPortal(runtime.browser,runtime.base,{role:'admin',section:'activity',historyError:'1'},390)
  await error.getByRole('button',{name:'Record changes',exact:true}).click()
  await error.getByRole('alert').waitFor()
  await error.evaluate(()=>{window.fixtureHistoryError=false})
  await error.getByRole('button',{name:'Retry changes',exact:true}).click()
  await error.locator('.record-history-event').first().waitFor()
  assert.deepEqual(error.portalErrors,[])
  await error.close()
  console.log('PASS record history connection failure and retry')
} finally { await runtime.close() }
