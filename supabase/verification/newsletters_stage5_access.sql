 blocked:=false;
 begin perform public.save_announcement_targets(n,'[{"campus":"junior","class_level":"","class_stream":""}]'); exception when others then blocked:=true; end;
 if not blocked or (select campus from public.announcement_targets where announcement_id=n)<>'senior' then raise exception 'Target replacement was not atomic'; end if;
 update public.announcements set state='published' where id in(n,junior);
 update public.announcements set state='published',published_at=now()+interval '1 day' where id=future_id;
 update public.announcements set state='published',published_at=now()-interval '2 days',expires_at=now()-interval '1 day' where id=expired;
 blocked:=false;
 begin perform public.save_announcement_targets(n,targets); exception when insufficient_privilege then blocked:=true; end;
 if not blocked then raise exception 'Published audience changed'; end if;
 reset role;
 insert into newsletter_checks values('Admin publishes; invalid audience rolls back; published audience locked');
 perform set_config('request.jwt.claim.sub',par::text,true);
 perform set_config('request.jwt.claims',jsonb_build_object('sub',par,'role','authenticated','aal','aal2')::text,true);
 set local role authenticated;
 response:=public.parent_school_updates(s.id,0,50);
 if not exists(select 1 from jsonb_array_elements(response->'items') e where e->>'id'=n::text)
 or exists(select 1 from jsonb_array_elements(response->'items') e where e->>'id' in(junior::text,future_id::text,expired::text,draft_id::text)) then raise exception 'Senior feed scope/release filter failed'; end if;
 response:=public.parent_school_updates(j.id,0,50);
 if not exists(select 1 from jsonb_array_elements(response->'items') e where e->>'id'=junior::text)
 or exists(select 1 from jsonb_array_elements(response->'items') e where e->>'id'=n::text) then raise exception 'Junior feed scope failed'; end if;
 insert into public.announcement_reads(announcement_id) values(n);
 response:=public.parent_school_updates(s.id);
 if not exists(select 1 from jsonb_array_elements(response->'items') e where e->>'id'=n::text and (e->>'acknowledged')::boolean) then raise exception 'Acknowledgement missing'; end if;
 blocked:=false;
 begin insert into public.announcement_reads(announcement_id,user_id) values(n,adm); exception when insufficient_privilege then blocked:=true; end;
 if not blocked then raise exception 'Reader impersonation permitted'; end if;
 blocked:=false;
 begin perform public.parent_school_updates(s.id,0,51); exception when invalid_parameter_value then blocked:=true; end;
 if not blocked then raise exception 'Unbounded page accepted'; end if;
 reset role;
 insert into newsletter_checks values('Selected child isolation, draft/future/expiry exclusion, own acknowledgement and page bounds');
 update public.parent_student set verified_at=null where parent_id=par and student_id=s.id;
 set local role authenticated;
 blocked:=false;
 begin perform public.parent_school_updates(s.id); exception when insufficient_privilege then blocked:=true; end;
 if not blocked then raise exception 'Revoked link retained feed'; end if;
 reset role;
 insert into newsletter_checks values('Revoked parent link denied');
 for actor in select id,active_role,campus from public.profiles where active_role in('teacher','accountant','parent') or (active_role='admin' and campus='junior') loop
 perform set_config('request.jwt.claim.sub',actor.id::text,true);
 perform set_config('request.jwt.claims',jsonb_build_object('sub',actor.id,'role','authenticated','aal','aal2')::text,true);
 set local role authenticated;
 blocked:=false;
 begin insert into public.announcements(campus,title) values('senior','Forbidden test'); exception when others then blocked:=true; end;
 if not blocked then raise exception 'Unauthorized newsletter creation: %',actor.active_role; end if;
 update public.announcements set title='Forbidden edit' where id=n;
 get diagnostics count_before=row_count;
 if count_before<>0 then raise exception 'Unauthorized newsletter edited'; end if;
 blocked:=false;
 begin insert into public.portal_content_files(announcement_id,extension,original_name,mime_type,size_bytes) values(n,'pdf','test.pdf','application/pdf',100); exception when others then blocked:=true; end;
 if not blocked then raise exception 'Unauthorized file reservation accepted'; end if;
 reset role;
 insert into newsletter_checks values('Denied edit/upload for '||actor.active_role||' '||coalesce(actor.campus,''));
 end loop;
 if not exists(select 1 from public.portal_content_events where announcement_id=n) then raise exception 'Trusted audit missing'; end if;
 if has_function_privilege('anon','public.parent_school_updates(uuid,integer,integer)','execute') or has_function_privilege('anon','public.save_announcement_targets(uuid,jsonb)','execute') then raise exception 'Anonymous execution allowed'; end if;
 insert into newsletter_checks values('Trusted audit present; anonymous RPC execution denied');
end;
$test$;
select count(*) as passed_groups, true as all_checks_passed from newsletter_checks;
rollback;
