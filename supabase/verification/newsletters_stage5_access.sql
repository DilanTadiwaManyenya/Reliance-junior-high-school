begin;
create temporary table newsletter_checks(label text);
do $test$
declare adm uuid; par uuid; j public.students; s public.students; n uuid:=gen_random_uuid(); junior uuid:=gen_random_uuid();
 future_id uuid:=gen_random_uuid(); expired uuid:=gen_random_uuid(); draft_id uuid:=gen_random_uuid();
 response jsonb; blocked boolean; actor record; targets jsonb; count_before integer;
begin
 select id into adm from public.profiles where active_role='admin' and campus='all' limit 1;
 select id into par from public.profiles where active_role='parent' limit 1;
 select * into j from public.students where campus='junior' and status='active' limit 1;
 select * into s from public.students where campus='senior' and status='active' limit 1;
 if adm is null or par is null or j.id is null or s.id is null then raise exception 'Required role fixtures unavailable'; end if;
 insert into public.parent_student(parent_id,student_id,verified_at) values(par,j.id,now()),(par,s.id,now()) on conflict(parent_id,student_id) do update set verified_at=excluded.verified_at;
 perform set_config('request.jwt.claim.sub',adm::text,true);
 perform set_config('request.jwt.claims',jsonb_build_object('sub',adm,'role','authenticated','aal','aal2')::text,true);
 set local role authenticated;
 insert into public.announcements(id,campus,title,body,category) values(n,'senior','Newsletter test Senior','Body','newsletter'),(junior,'junior','Newsletter test Junior','Body','newsletter'),(future_id,'senior','Newsletter test Future','Body','newsletter'),(expired,'senior','Newsletter test Expired','Body','newsletter'),(draft_id,'senior','Newsletter test Draft','Body','newsletter');
 targets:=jsonb_build_array(jsonb_build_object('campus','senior','class_level',s.class_level,'class_stream',coalesce(s.class_stream,'')));
 perform public.save_announcement_targets(n,targets);
 perform public.save_announcement_targets(future_id,targets);
 perform public.save_announcement_targets(expired,targets);
 perform public.save_announcement_targets(draft_id,targets);
