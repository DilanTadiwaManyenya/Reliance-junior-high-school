-- Uses actual role identities. All fixture content and audit entries roll back.
begin;
create temporary table support_checks(label text);
do $test$
declare a record; j record; adm uuid; r uuid:=gen_random_uuid(); jr uuid:=gen_random_uuid(); n uuid:=gen_random_uuid(); draft_n uuid:=gen_random_uuid();
 file_id uuid:=gen_random_uuid(); response jsonb; actor record; scope text; blocked boolean; changed integer;
begin
 select x.* into a from public.teacher_class_subject_assignments x join public.profiles p on p.id=x.teacher_id where x.campus='senior' and p.active_role='teacher' limit 1;
 select x.*,c.subject into j from public.teacher_class_assignments x join public.profiles p on p.id=x.teacher_id join public.library_curriculum_subjects c on c.class_level=x.class_level where x.campus='junior' and p.active_role='teacher' limit 1;
 select id into adm from public.profiles where active_role='admin' and campus='all' limit 1;
 if a.teacher_id is null or j.teacher_id is null or adm is null then raise exception 'Required roles unavailable'; end if;
 perform set_config('request.jwt.claim.sub',a.teacher_id::text,true);
 perform set_config('request.jwt.claims',jsonb_build_object('sub',a.teacher_id,'role','authenticated','aal','aal2')::text,true);
 set local role authenticated;
 insert into public.learning_resources(id,campus,class_level,class_stream,subject,academic_year,term,title,description) values(r,'senior',a.class_level,a.class_stream,a.subject,2026,3,'Stage6 Senior probe','Support fixture');
 reset role;
 perform set_config('request.jwt.claim.sub',j.teacher_id::text,true);
 perform set_config('request.jwt.claims',jsonb_build_object('sub',j.teacher_id,'role','authenticated','aal','aal2')::text,true);
 set local role authenticated;
 insert into public.learning_resources(id,campus,class_level,class_stream,subject,academic_year,term,title) values(jr,'junior',j.class_level,j.class_stream,j.subject,2026,3,'Stage6 Junior probe');
 reset role;
 insert into public.portal_content_files(id,resource_id,extension,original_name,mime_type,size_bytes,uploaded_by,ready,active) values(file_id,r,'pdf','senior.pdf','application/pdf',100,a.teacher_id,true,true);
 perform set_config('request.jwt.claim.sub',adm::text,true);
 perform set_config('request.jwt.claims',jsonb_build_object('sub',adm,'role','authenticated','aal','aal2')::text,true);
 set local role authenticated;
 insert into public.announcements(id,title,body,campus) values(n,'Stage6 Both newsletter','Support fixture','all'),(draft_n,'Stage6 Draft newsletter','Private draft','senior');
 perform public.save_announcement_targets(n,'[{"campus":"junior","class_level":"","class_stream":""},{"campus":"senior","class_level":"","class_stream":""}]');
 update public.announcements set state='published' where id=n;
 response:=public.school_library_oversight('all','notes','','','Stage6');
 if (response->>'total_count')::integer<>2 then raise exception 'Main Admin lost both-campus visibility'; end if;
 response:=public.school_content_trace('newsletters',n);
 if not (response->>'audit_visible')::boolean or jsonb_array_length(response->'events')=0 then raise exception 'Main Admin newsletter audit missing'; end if;
 reset role;
 insert into support_checks values('Main Admin reads both campuses and both-campus audit');

 for actor in select id,active_role,campus,portal_access_enabled from public.profiles where active_role in('admin','accountant','teacher','parent') loop
 perform set_config('request.jwt.claim.sub',actor.id::text,true);
 perform set_config('request.jwt.claims',jsonb_build_object('sub',actor.id,'role','authenticated','aal','aal2')::text,true);
 set local role authenticated;
 if actor.active_role in ('teacher','parent') or actor.campus is null or actor.campus not in ('all','junior','senior') or actor.portal_access_enabled is false or not public.has_active_role(actor.active_role) or (actor.active_role='accountant' and actor.campus='all') then
   blocked:=false;
   begin perform public.school_library_oversight('senior'); exception when insufficient_privilege then blocked:=true; end;
   if not blocked then raise exception 'Unapproved support role %',actor.active_role; end if;
   blocked:=false;
   begin perform public.school_content_trace('notes',r); exception when insufficient_privilege then blocked:=true; end;
   if not blocked then raise exception 'Unapproved audit role %',actor.active_role; end if;
 else
   scope:=case when actor.campus='all' then 'all' else actor.campus end;
   response:=public.school_library_oversight(scope,'notes','','','Stage6');
   if actor.campus<>'all' and exists(select 1 from jsonb_array_elements(response->'items') e where e->>'campus'<>actor.campus) then raise exception 'Other campus leaked'; end if;
   if not exists(select 1 from jsonb_array_elements(response->'items') e where e->>'id'=case when actor.campus='junior' then jr::text else r::text end) then raise exception 'Own campus support fixture missing'; end if;
   if actor.campus<>'all' then
     blocked:=false;
     begin perform public.school_library_oversight('all'); exception when insufficient_privilege then blocked:=true; end;
     if not blocked then raise exception 'Campus actor accessed all campuses'; end if;
     blocked:=false;
     begin perform public.school_library_oversight(case when actor.campus='junior' then 'senior' else 'junior' end); exception when insufficient_privilege then blocked:=true; end;
     if not blocked then raise exception 'Campus argument bypassed scope'; end if;
     blocked:=false;
     begin perform public.school_content_trace('notes',case when actor.campus='junior' then r else jr end); exception when insufficient_privilege then blocked:=true; end;
     if not blocked then raise exception 'Cross-campus audit exposed'; end if;
   end if;
   response:=public.school_content_trace('notes',case when actor.campus='junior' then jr else r end);
   if jsonb_array_length(response->'events')=0 then raise exception 'Own campus audit absent'; end if;
   if jsonb_path_exists(response,'$.**.actor_id') or jsonb_path_exists(response,'$.**.phone') or jsonb_path_exists(response,'$.**.email') then raise exception 'Private actor details exposed'; end if;
   update public.learning_resources set title='Forbidden support edit' where id in(r,jr);
   get diagnostics changed=row_count;
   if changed<>0 then raise exception 'Support edited teacher notes'; end if;
   blocked:=false;
   begin insert into public.portal_content_files(resource_id,extension,original_name,mime_type,size_bytes) values(r,'pdf','support.pdf','application/pdf',100); exception when others then blocked:=true; end;
   if not blocked then raise exception 'Support role uploaded teacher notes'; end if;
   response:=public.school_library_oversight(scope,'newsletters','','','Stage6');
   if not exists(select 1 from jsonb_array_elements(response->'items') e where e->>'id'=n::text) then raise exception 'Published both-campus newsletter missing'; end if;
   if actor.active_role='accountant' and exists(select 1 from jsonb_array_elements(response->'items') e where e->>'id'=draft_n::text) then raise exception 'Accountant saw newsletter draft'; end if;
   response:=public.school_content_trace('newsletters',n);
   if actor.campus<>'all' and ((response->>'audit_visible')::boolean or jsonb_array_length(response->'events')<>0) then raise exception 'Both-campus audit exposed outside Main Admin'; end if;
   if actor.campus='senior' and not public.portal_storage_file_access('learning-library',r::text||'/'||file_id::text||'.pdf',false) then raise exception 'Own campus current file denied'; end if;
   if actor.campus='junior' and public.portal_storage_file_access('learning-library',r::text||'/'||file_id::text||'.pdf',false) then raise exception 'Other campus file allowed'; end if;
 end if;
 reset role;
 insert into support_checks values('Scope and permission checks for '||actor.active_role||' '||coalesce(actor.campus,''));
 end loop;
 perform set_config('request.jwt.claim.sub',adm::text,true);
 perform set_config('request.jwt.claims',jsonb_build_object('sub',adm,'role','authenticated','aal','aal2')::text,true);
 set local role authenticated;
 response:=public.school_library_oversight('senior','notes','draft',a.class_level,'Stage6 Senior',0,1);
 if response->>'total_count'<>'1' or jsonb_array_length(response->'items')<>1 then raise exception 'State/grade/search/page filters failed'; end if;
 blocked:=false;
 begin perform public.school_library_oversight('all','notes','','','',0,51); exception when invalid_parameter_value then blocked:=true; end;
 if not blocked then raise exception 'Unbounded support page'; end if;
 blocked:=false;
 begin perform public.school_content_trace('notes',r,0,51); exception when invalid_parameter_value then blocked:=true; end;
 if not blocked then raise exception 'Unbounded trace page'; end if;
 reset role;
 if has_function_privilege('anon','public.school_library_oversight(text,text,text,text,text,integer,integer)','execute') or has_function_privilege('anon','public.school_content_trace(text,uuid,integer,integer)','execute') then raise exception 'Anonymous support execution granted'; end if;
 insert into support_checks values('Search/state/grade/page validation and anonymous denial');
end;
$test$;
select count(*) as passed_groups,true as all_checks_passed from support_checks;
rollback;
